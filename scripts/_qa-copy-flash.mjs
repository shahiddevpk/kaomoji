import { chromium } from "playwright";
const browser = await chromium.launch({ channel: "msedge", headless: true });
const context = await browser.newContext();
await context.grantPermissions(["clipboard-read","clipboard-write"], { origin: "http://127.0.0.1:3000" });
const page = await context.newPage();
page.on("pageerror", (e) => console.log("PAGEERR", e.message));
page.on("console", (m) => { if (m.type() === "error") console.log("ERR", m.text()); });
await page.goto("http://127.0.0.1:3000/cute-kaomoji", { waitUntil: "networkidle", timeout: 90000 });
await page.waitForTimeout(1500);
const btn = page.locator("button.kaomoji-copy").first();
await btn.waitFor({ state: "visible" });
const before = await btn.innerText();
await btn.click();
await page.waitForTimeout(500);
const text = await btn.innerText();
const attr = await btn.getAttribute("data-copied");
const bg = await btn.evaluate((el) => getComputedStyle(el).backgroundColor);
const recent = await page.evaluate(() => localStorage.getItem("pastekaomoji-recent")?.length ?? 0);
console.log(JSON.stringify({ before, text, attr, bg, recentLen: recent, pass: attr === "copied" && /copied/i.test(text) }));
await browser.close();